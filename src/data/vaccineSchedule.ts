// ===== قالب جدول التطعيمات الرسمي (Vaccine Schedule Template) =====
//
// هذا الملف يفصل «القالب الرسمي» (اسم التطعيم، العمر المستحق، رقم الجرعة)
// عن «سجل جرعات الطفل الفعلي» المخزَّن عبر dataService (تاريخ الإعطاء،
// أُعطيت أم لا، ملاحظات). القالب لا يُخزَّن في بيانات الطفل — هو مرجع ثابت
// تُشير إليه سجلات الطفل عبر templateId، حتى يمكن تحديث القالب لاحقًا
// (رفع scheduleVersion، إضافة جرعات جديدة) دون فقدان أو تحريف تاريخ
// أي جرعة سُجّلت فعليًا لطفل معيّن.
//
// ✅ تم التحقق من هذا الجدول مقابل «شهادة التطعيم» الرسمية الصادرة عن
// وزارة الصحة السعودية (الجدول الوطني للتطعيمات المطبوع على شهادة
// التطعيم الرسمية — نفس الجدول المستخدم في بطاقة "صحتي")، بعد أن تعذّر
// الوصول لصفحة وزارة الصحة إلكترونيًا (HTTP 403 بسبب سياسة شبكة بيئة
// التنفيذ) وزوّد المستخدم نسخة رسمية من الشهادة مباشرة لمطابقتها جرعة
// بجرعة. كل جرعة أدناه منقولة حرفيًا من جدول "Vaccine / التطعيم" في تلك
// الشهادة (الزيارات: عند الولادة، شهرين، ٤ أشهر، ٦ أشهر، ٩ أشهر، ١٢ شهر،
// ١٨ شهر، ٢٤ شهر، ودخول الصف الأول الابتدائي).
//
// المرجع النهائي يبقى دائمًا شهادة التطعيم الورقية/بطاقة "صحتي" الخاصة
// بالطفل، فقد تُحدَّث وزارة الصحة الجدول لاحقًا.

export interface VaccineTemplateEntry {
  /** معرّف ثابت لا يتغيّر بين إصدارات القالب — تُشير إليه سجلات جرعات الطفل */
  id: string
  /** اسم التطعيم */
  vaccineName: string
  /** وصف الجرعة (مثال: "الجرعة الأولى"، "جرعة معزّزة") */
  doseLabel: string
  /** العمر المستحق بالأشهر (0 = عند الولادة) */
  dueMonths: number
  /** هل تم التحقق من هذه الجرعة مقابل المصدر الرسمي في هذه الجلسة؟ */
  verified: boolean
  /** يحتاج مراجعة بشرية قبل الاعتماد عليه بثقة كاملة */
  needsReview: boolean
  /** ملاحظة توضيحية (تظهر في الواجهة عند needsReview) */
  note?: string
}

export interface VaccineScheduleTemplate {
  /** رقم إصدار القالب — يُرفع عند أي تعديل على الجرعات */
  scheduleVersion: string
  /** رابط المصدر الرسمي المعتمد */
  sourceUrl: string
  /** تاريخ اعتماد هذا الإصدار من الجدول (ISO) */
  effectiveAt: string
  entries: VaccineTemplateEntry[]
}

