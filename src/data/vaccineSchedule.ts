// ===== قالب جدول التطعيمات الرسمي (Vaccine Schedule Template) =====
//
// هذا الملف يفصل «القالب الرسمي» (اسم التطعيم، العمر المستحق، رقم الجرعة)
// عن «سجل جرعات الطفل الفعلي» المخزَّن عبر dataService (تاريخ الإعطاء،
// أُعطيت أم لا، ملاحظات). القالب لا يُخزَّن في بيانات الطفل — هو مرجع ثابت
// تُشير إليه سجلات الطفل عبر templateId، حتى يمكن تحديث القالب لاحقًا
// (رفع scheduleVersion، إضافة جرعات جديدة) دون فقدان أو تحريف تاريخ
// أي جرعة سُجّلت فعليًا لطفل معيّن.
//
// ⚠️ محاولة التحقق من المصدر الرسمي:
// حاولنا في هذه الجلسة جلب صفحة وزارة الصحة الرسمية
// https://www.moh.gov.sa/healthawareness/educationalcontent/vaccination/pages/vaccination1.aspx
// (وأيضًا نسخة PDF رسمية بديلة ونسخة مؤرشفة عبر web.archive.org)
// عبر أداة WebFetch، لكن جميع المحاولات فشلت بخطأ HTTP 403 — سياسة الشبكة
// في بيئة التنفيذ ترفض الاتصال بنطاق moh.gov.sa وأرشيف الويب بالكامل
// (rejection من بوابة الشبكة نفسها قبل الوصول للخادم، وليس رفضًا من
// الموقع). بحثنا أيضًا عبر WebSearch عن نص الجدول لكن النتائج كانت
// ملخّصات من مواقع طبية غير رسمية (وليست نصّ وزارة الصحة نفسه)، فلم
// نعتمد عليها كمصدر رسمي موثّق.
//
// نتيجة لذلك: لم نتمكّن من التحقق من أي جرعة في هذا الجدول مقابل نص
// الصفحة الرسمية في هذه الجلسة. الجدول أدناه هو استمرار للجدول
// الاسترشادي الذي كان موجودًا مسبقًا في الكود (مبني أصلًا على الجدول
// الوطني السعودي المعتاد)، لكننا وضعنا `verified: false` و
// `needsReview: true` على كل جرعاته لأننا لا نستطيع تأكيد دقّتها من
// المصدر الرسمي المطلوب في هذه الجلسة. يجب على مراجع بشري مطابقتها
// يدويًا مع صفحة وزارة الصحة أو منصة «صحّتي» قبل الاعتماد الكامل عليها.

export interface VaccineTemplateEntry {
  /** معرّف ثابت لا يتغيّر بين إصدارات القالب — تُشير إليه سجلات جرعات الطفل */
  id: string
  /** اسم التطعيم */
  vaccineName: string
  /** وصف الجرعة (مثال: "الجرعة الأولى"، "جرعة معزّزة") */
  doseLabel: string
  /** العمر المستحق بالأشهر (0 = عند الولادة) */
  dueMonths: number
  /** هل تم التحقق من هذه الجرعة مقابل المصدر الرسمي في هذه الجلسة؟ */
  verified: boolean
  /** يحتاج مراجعة بشرية قبل الاعتماد عليه بثقة كاملة */
  needsReview: boolean
  /** ملاحظة توضيحية (تظهر في الواجهة عند needsReview) */
  note?: string
}

export interface VaccineScheduleTemplate {
  /** رقم إصدار القالب — يُرفع عند أي تعديل على الجرعات */
  scheduleVersion: string
  /** رابط المصدر الرسمي المعتمد */
  sourceUrl: string
  /** تاريخ اعتماد هذا الإصدار من الجدول (ISO) */
  effectiveAt: string
  entries: VaccineTemplateEntry[]
}

